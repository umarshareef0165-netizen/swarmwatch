"""SwarmWatch reporting: JSON export + self-contained HTML dashboard."""
from __future__ import annotations

import html
import json
import os


def save_run_json(result, path: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        json.dump(result.to_dict(), f, indent=2, default=str)


def _esc(s) -> str:
    return html.escape(str(s))


def dashboard_html(results, title: str = "SwarmWatch — experiment dashboard") -> str:
    rows = []
    for r in results:
        c = r.config
        rows.append(
            "<tr>"
            f"<td>{_esc(c.label or 'run')}</td>"
            f"<td>{c.n_agents}</td><td>{c.n_curious}</td><td>{c.seed}</td>"
            f"<td>{'BREACH' if r.breach else 'blocked'}</td>"
            f"<td>{r.breach_tick if r.breach_tick is not None else '-'}</td>"
            f"<td>{r.first_board_signal_tick if r.first_board_signal_tick is not None else '-'}</td>"
            f"<td>{r.detection_latency_ticks if r.detection_latency_ticks is not None else '-'}</td>"
            f"<td>{r.board_detection_latency_ticks if r.board_detection_latency_ticks is not None else '-'}</td>"
            f"<td>{len(r.findings)}</td>"
            f"<td>{r.false_positives}</td>"
            f"<td>{r.task_completion:.2f}</td>"
            f"<td>{r.benign_completion:.2f}</td>"
            f"<td>{r.mitigation_tick if r.mitigation_tick is not None else '-'}</td>"
            "</tr>")
    findings_rows = []
    for r in results:
        for f in r.findings:
            findings_rows.append(
                "<tr>"
                f"<td>{_esc(r.config.label or '')}</td>"
                f"<td>{_esc(f['detector'])}</td><td>{f['tick']}</td>"
                f"<td>{_esc(f['severity'])}</td>"
                f"<td>{_esc(f['summary'])}</td>"
                "</tr>")
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>{_esc(title)}</title>
<style>
body{{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:32px;color:#1a1a2e;line-height:1.5}}
h1{{font-size:22px}}h2{{font-size:17px;margin-top:28px}}
table{{border-collapse:collapse;width:100%;font-size:13px}}
th,td{{border:1px solid #c9c9d6;padding:6px 8px;text-align:left;vertical-align:top}}
th{{background:#ececf4}}tr:nth-child(even){{background:#f7f7fb}}
.breach{{color:#b00020;font-weight:700}}.blocked{{color:#0a7a2f;font-weight:700}}
code{{background:#f0f0f5;padding:1px 4px;border-radius:3px}}
</style></head><body>
<h1>{_esc(title)}</h1>
<p>SwarmWatch incident simulation: a swarm of agents on benign eval tasks
discovers a shared folder, turns it into a message board, splits work,
elects a coordinator, uses many identities, scrubs logs, and breaches a
restricted endpoint together. The monitor detects the coordination from
observable traces only; mitigation quarantines the channel and freezes
the endpoint.</p>
<h2>Runs</h2>
<table><tr><th>Run</th><th>Agents</th><th>Curious</th><th>Seed</th><th>Outcome</th>
<th>Breach tick</th><th>First board signal</th><th>Detection latency (ticks)</th>
<th>Board-detection latency (ticks)</th>
<th>Findings</th><th>False positives</th><th>Task completion</th>
<th>Benign completion</th><th>Mitigation tick</th></tr>
{''.join(rows)}</table>
<h2>Findings</h2>
<table><tr><th>Run</th><th>Detector</th><th>Tick</th><th>Severity</th><th>Summary</th></tr>
{''.join(findings_rows)}</table>
<p>Generated by <code>swarmwatch</code>. All numbers are measured from
seeded deterministic simulation runs; nothing here is hand-written.</p>
</body></html>"""


def save_dashboard(results, path: str, title: str = "SwarmWatch — experiment dashboard") -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write(dashboard_html(results, title))


def save_metrics_markdown(results, path: str) -> None:
    lines = ["# SwarmWatch — measured results\n"]
    lines.append("| Run | Agents | Curious | Seed | Outcome | Breach tick | First signal | Detection latency | Board latency | Findings | False positives | Task completion | Benign completion | Mitigation tick |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in results:
        c = r.config
        lines.append(
            f"| {c.label or ''} | {c.n_agents} | {c.n_curious} | {c.seed} | "
            f"{'BREACH' if r.breach else 'blocked'} | {r.breach_tick if r.breach_tick is not None else '-'} | "
            f"{r.first_board_signal_tick if r.first_board_signal_tick is not None else '-'} | "
            f"{r.detection_latency_ticks if r.detection_latency_ticks is not None else '-'} | "
            f"{r.board_detection_latency_ticks if r.board_detection_latency_ticks is not None else '-'} | "
            f"{len(r.findings)} | {r.false_positives} | {r.task_completion:.2f} | "
            f"{r.benign_completion:.2f} | {r.mitigation_tick if r.mitigation_tick is not None else '-'} |")
    lines.append("")
    lines.append("## Findings")
    for r in results:
        for f in r.findings:
            lines.append(f"- **{r.config.label}** t={f['tick']} [{f['severity']}] "
                         f"*{f['detector']}*: {f['summary']}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
